def render_project(plan: MCPcastPlan) -> dict[str, str]:
    """Every generated file for *plan*, keyed by path relative to the project root.

    Includes both the derived files (rewritten on every regeneration) and the
    scaffold files in :data:`SCAFFOLD_ONCE` (written only when absent).
    """
    pkg = package_name(plan.api.name)
    groups = _groups(plan)
    files: dict[str, str] = {
        "server.py": _render_launcher(plan),
        f"{pkg}/__init__.py": _render_package_init(plan),
        f"{pkg}/__main__.py": _render_main(plan),
        f"{pkg}/config.py": _render_config(plan),
        f"{pkg}/upstream.py": _render_upstream(plan),
        f"{pkg}/approval.py": _render_approval(plan),
        f"{pkg}/server.py": _render_server_module(plan),
        f"{pkg}/tools/__init__.py": _render_tools_init(plan, groups),
    }
    for group, tools in groups:
        files[f"{pkg}/tools/{group}.py"] = _render_tools_module(plan, group, tools)
    files["tests/conftest.py"] = _render_conftest(plan)
    files["tests/test_tools.py"] = _render_tests(plan)
    files["README.md"] = render_readme(plan)
    files["pyproject.toml"] = _render_pyproject(plan)
    files["Dockerfile"] = _render_dockerfile(plan)
    files[".env.example"] = _render_env_example(plan)
    files[".gitignore"] = _GITIGNORE
    return files


