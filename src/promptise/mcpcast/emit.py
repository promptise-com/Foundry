def _tools_table(plan: MCPcastPlan) -> str:
    if not plan.tools:
        return "_No tools are exposed under this profile._\n"
    rows = ["| Tool | Risk | Approval | Upstream operations |", "|---|---|---|---|"]
    for t in plan.tools:
        ops = ", ".join(
            _md_code(f"{r.method} {r.path}") + (f" on {_md_code(r.base_url)}" if r.base_url else "")
            for r in t.routes
        )
        rows.append(
            f"| `{t.name}` | {t.risk.value} | {'**required**' if t.requires_approval else '—'} | {ops} |"
        )
    return "\n".join(rows) + "\n"


def _dropped_table(plan: MCPcastPlan) -> str:
    if not plan.dropped:
        return "_Every operation in the spec is exposed._\n"
    rows = ["| Operation | Why it is not a tool |", "|---|---|"]
    rows.extend(f"| {_md_code(d.operation_id)} | {_md_cell(d.reason)} |" for d in plan.dropped)
    return "\n".join(rows) + "\n"


_MD_SPECIALS = str.maketrans({"\\": "\\\\", "`": "\\`", "|": "\\|", "<": "\\<", "[": "\\["})


def _md_cell(text: str) -> str:
    """Plan text as inert Markdown: no control characters, no links, tags, code or pipes."""
    return _CONTROL.sub(" ", _writable(text)).translate(_MD_SPECIALS)


def _md_code(text: str) -> str:
    """*text* in a Markdown code span, whatever it contains.

    Backslash escapes do not work inside a code span, so a text with backticks
    gets a longer fence; a pipe is escaped because the span sits in a table.
    """
    cleaned = _CONTROL.sub(" ", _writable(text)).replace("|", "\\|")
    longest = max((len(run) for run in re.findall(r"`+", cleaned)), default=0)
    fence = "`" * (longest + 1)
    padding = " " if cleaned.startswith("`") or cleaned.endswith("`") else ""
    return f"{fence}{padding}{cleaned}{padding}{fence}"


_MINT_KEY = "python -c 'import secrets; print(\"sk-\" + secrets.token_urlsafe(32))'"
"""How the README tells the operator to mint an MCP client key."""


def _credential_words(plan: MCPcastPlan) -> tuple[str, str]:
    """``(slot, example)`` of the upstream credential as the README names it.

    The slot is where the API expects it — ``the `X-API-Key` header``, ``the
    `api_key` query parameter`` — from the spec's security scheme; the
    example is the value shape (``Bearer <your API token>`` for the
    ``Authorization`` header, ``<your API key>`` otherwise).
    """
    location, name = _credential_scheme(plan)
    slot = f"the `{name}` header" if location == "header" else f"the `{name}` query parameter"
    example = (
        "Bearer <your API token>"
        if plan.api.credential_is_authorization_header
        else "<your API key>"
    )
    return slot, example


def _auth_section(plan: MCPcastPlan) -> str:
    mode = plan.api.auth
    slot, example = _credential_words(plan)
    if mode is AuthMode.PASSTHROUGH:
        # The plan refuses passthrough for any scheme but the Authorization header,
        # so the relayed header and the spec's slot are one and the same here.
        return (
            "**Auth mode: `passthrough`.** The server forwards the `Authorization` header "
            "of the current request (a bearer token: `Bearer <token>`) to the upstream API "
            "unchanged — a call acts with the caller's credential on that request. Connect "
            "over HTTP/SSE and send the header; calls without one fail with "
            "`UPSTREAM_AUTH_MISSING`. Desktop clients that launch `server.py` over stdio "
            "cannot send headers — for a personal server, regenerate with "
            "`--auth env-token`.\n\n"
            "> **This server authenticates nobody itself.** It is an unauthenticated relay: "
            "anyone who can reach its port can list the tools and drive the upstream API "
            "with whatever bearer token they present, from this server's network position. "
            "Deploy it only behind a gateway that authenticates MCP clients, or regenerate "
            "with `--auth api-key` to have the server authenticate them.\n"
        )
    if mode is AuthMode.ENV_TOKEN:
        return (
            "**Auth mode: `env-token`.** Every upstream call presents one credential "
            f"from the environment, sent as {slot} (the spec's security scheme) — the "
            "usual setup for a personal server launched over stdio by Claude Desktop, "
            "Claude Code or Cursor. Calls fail with `UPSTREAM_AUTH_MISSING` until it is "
            "set, in the client's config (see *Connect an AI*) or in `.env` next to "
            "`server.py`:\n\n"
            "```bash\n"
            f"export MCPCAST_UPSTREAM_TOKEN='{example}'\n"
            "```\n\n"
            "> **Over HTTP this server is an unauthenticated proxy for that credential:** "
            "anyone who can reach its port acts with your token. It therefore binds "
            "loopback only (in `python server.py`, `promptise serve` and "
            "`promptise mcpcast --serve` alike) unless you pass `--public` (or set "
            "`MCPCAST_PUBLIC=1`) — do that only behind an authenticating gateway.\n\n"
            "For a shared HTTP deployment where each caller must act as themselves, "
            "regenerate with `--auth passthrough` or `--auth api-key`.\n"
        )
    if mode is AuthMode.API_KEY:
        return (
            "**Auth mode: `api-key`.** MCP clients present an API key in the `x-api-key` "
            "header. Each key names a tenant, and each tenant has its own upstream "
            f"credential, sent as {slot} — clients never see the upstream secret. "
            "`MCPCAST_CLIENT_KEYS` is read once at start-up (rotating keys needs a "
            "restart); `MCPCAST_UPSTREAM_TOKENS` is read on every call, so upstream "
            "credentials rotate without a restart. Mint each client key — the server "
            "refuses to start with no key, with a `<placeholder>` key or with a key copied "
            "from documentation (`sk-acme`, `sk-reviewer`), which anyone can read:\n\n"
            "```bash\n"
            f"{_MINT_KEY}\n"
            'export MCPCAST_CLIENT_KEYS=\'{"sk-<generated>": {"client_id": "acme-agent", '
            '"tenant_id": "acme", "roles": []}}\'\n'
            f'export MCPCAST_UPSTREAM_TOKENS=\'{{"acme": "{example}"}}\'\n'
            "```\n"
        )
    return (
        "**Auth mode: `none`.** Calls to the upstream API carry no credentials. This is "
        "for local development only — the server binds loopback only (in "
        "`python server.py`, `promptise serve` and `promptise mcpcast --serve` alike) "
        "unless you pass `--public` (or set `MCPCAST_PUBLIC=1`), and then anyone who "
        "reaches the port drives the upstream API from this server's network position. "
        "Regenerate with `--auth env-token`, `--auth passthrough` or `--auth api-key` "
        "before exposing it.\n"
    )


def _approval_section(plan: MCPcastPlan) -> str:
    if not plan.gated_tools:
        return (
            f"No tool in this plan changes data (profile `{plan.profile.value}`), so no "
            "approval gate is installed.\n"
        )
    names = ", ".join(f"`{t.name}`" for t in plan.gated_tools)
    head = (
        f"These tools change or delete data and are **approval-gated server-side** — any "
        f"MCP client, not just Promptise agents, is held until a human decides, and a "
        f"timeout denies by default: {names}.\n\n"
    )
    hidden = [
        f"`{t.name}` always sends "
        + ", ".join(
            _md_code(f"{n}={json.dumps(p.default, default=str)}")
            for n, p in t.params.items()
            if p.hidden
        )
        for t in plan.gated_tools
        if any(p.hidden for p in t.params.values())
    ]
    fixed_note = (
        "Fixed values the plan hides from the agent are sent on every call and are "
        "listed in each tool's description so reviewers know what runs: "
        + "; ".join(hidden)
        + ".\n\n"
        if hidden
        else ""
    )
    if plan.api.approval_mode is ApprovalMode.PENDING:
        return (
            head
            + fixed_note
            + (
                "**Approval mode: `pending`** (independent four-eyes review, scoped to the "
                "tenant). A gated call waits in a pending store; a reviewer of the **same "
                "tenant** holding the `approver` role lists and decides it with the "
                "`approvals_list` / `approvals_decide` tools. A caller can never approve their "
                "own request, and reviewers never see other tenants' calls. Capacity is "
                "bounded too: at most `MCPCAST_MAX_PENDING` calls wait server-wide, "
                "`MCPCAST_MAX_PENDING_PER_TENANT` per tenant and "
                "`MCPCAST_MAX_PENDING_PER_CLIENT` per API key — beyond a cap the call is "
                "denied at once, so one tenant cannot fill the store for the others.\n\n"
                "Reviewers are MCP clients whose key in `MCPCAST_CLIENT_KEYS` carries the "
                "`approver` role and the tenant they review for (mint every key with "
                f"`{_MINT_KEY}`; the server refuses placeholder and documentation keys):\n\n"
                "```bash\n"
                'export MCPCAST_CLIENT_KEYS=\'{"sk-<agent key>": {"client_id": "acme-agent", '
                '"tenant_id": "acme", "roles": []}, '
                '"sk-<reviewer key>": {"client_id": "dana", "tenant_id": "acme", '
                '"roles": ["approver"]}}\'\n'
                "```\n"
            )
        )
    return (
        head
        + fixed_note
        + (
            "**Approval mode: `elicitation`** (confirm your own action). The human behind the "
            "calling MCP client is asked to approve through MCP elicitation. If the client "
            "cannot elicit, the call is **denied** — never silently allowed. A Promptise "
            "agent asks its own approval handler: pass `approval=` to `build_agent()` (for "
            "example `approval=CallbackApprovalHandler(ask_human)`); without it the agent "
            "cannot elicit. Independent four-eyes review (`api.approval: pending`) needs "
            "identified callers and is available with `--auth api-key`.\n"
        )
    )


_LOCAL_MCP_URL = "http://127.0.0.1:8080/mcp"


def _client_note(plan: MCPcastPlan) -> str:
    """A warning for auth modes a stdio desktop client cannot satisfy."""
    if plan.api.auth is AuthMode.ENV_TOKEN:
        return (
            "> The credential goes in the client's own config below — a desktop client "
            "launched from the GUI does not inherit your shell, so `export "
            "MCPCAST_UPSTREAM_TOKEN=…` in a terminal will not reach it.\n\n"
        )
    if plan.api.auth in (AuthMode.PASSTHROUGH, AuthMode.API_KEY):
        header = "Authorization" if plan.api.auth is AuthMode.PASSTHROUGH else "x-api-key"
        return (
            f"> **This server needs an `{header}` header on every request, which a stdio "
            "client cannot send.** Run it over HTTP (`python server.py --transport http`) "
            "and point your client at `http://127.0.0.1:8080/mcp` with the header, or "
            "regenerate with `--auth env-token` for a personal stdio server.\n\n"
        )
    return ""


def _stdio_snippets(plan: MCPcastPlan) -> str:
    """The client configs for auth modes ``none`` and ``env-token``: the client launches ``server.py``.

    Under ``env-token`` every snippet carries the credential itself — a
    desktop client launched from the GUI has no shell to inherit it from.
    """
    name = plan.api.name
    env_token = plan.api.auth is AuthMode.ENV_TOKEN
    token = _credential_words(plan)[1]
    env_json = f', "env": {{"MCPCAST_UPSTREAM_TOKEN": "{token}"}}' if env_token else ""
    env_flag = f' -e MCPCAST_UPSTREAM_TOKEN="{token}"' if env_token else ""
    if env_token:
        servers = (
            "    servers={\n"
            f'        "{name}": StdioServerSpec(\n'
            '            command="python",\n'
            '            args=["server.py"],\n'
            f'            env={{"MCPCAST_UPSTREAM_TOKEN": "{token}"}},\n'
            "        )\n"
            "    },\n"
        )
    else:
        servers = (
            f'    servers={{"{name}": StdioServerSpec(command="python", args=["server.py"])}},\n'
        )
    desktop_json = (
        "```json\n"
        "{\n"
        '  "mcpServers": {\n'
        f'    "{name}": {{ "command": "python", "args": ["/absolute/path/to/server.py"]{env_json} }}\n'
        "  }\n"
        "}\n"
        "```\n"
    )
    return (
        f"**Claude Desktop** — add to `claude_desktop_config.json`:\n\n{desktop_json}\n"
        "**Claude Code:**\n\n"
        "```bash\n"
        f"claude mcp add {name}{env_flag} -- python /absolute/path/to/server.py\n"
        "```\n\n"
        f"**Cursor** — add to `.cursor/mcp.json`:\n\n{desktop_json}\n"
        "**Promptise agent:**\n\n"
        "```python\n"
        "from promptise import build_agent, StdioServerSpec\n"
        "\n"
        "agent = await build_agent(\n"
        '    model="openai:gpt-5-mini",\n'
        f"{servers}"
        ")\n"
        "```\n"
    )


def _http_snippets(plan: MCPcastPlan) -> str:
    """The client configs for auth modes ``api-key`` and ``passthrough``: HTTP plus a header.

    No stdio config can work — the server reads the caller's identity from a
    request header — so the clients that can send one are shown, and Claude
    Desktop, which cannot, is named as such rather than given a config that
    fails.
    """
    name = plan.api.name
    if plan.api.auth is AuthMode.API_KEY:
        header, value = "x-api-key", "<key>"
        what = "one of the keys in `MCPCAST_CLIENT_KEYS`"
        spec_auth = 'api_key="<key>"'
    else:
        header, value = "Authorization", "Bearer <token>"
        what = "the caller's own upstream bearer token"
        spec_auth = 'bearer_token="<token>"'
    return (
        f"Run the server over HTTP and give every client the `{header}` header ({what}):\n\n"
        "```bash\n"
        f"python server.py --transport http        # {_LOCAL_MCP_URL}\n"
        "```\n\n"
        "**Claude Code:**\n\n"
        "```bash\n"
        f'claude mcp add {name} --transport http {_LOCAL_MCP_URL} --header "{header}: {value}"\n'
        "```\n\n"
        "**Cursor** — add to `.cursor/mcp.json`:\n\n"
        "```json\n"
        "{\n"
        '  "mcpServers": {\n'
        f'    "{name}": {{ "url": "{_LOCAL_MCP_URL}", "headers": {{ "{header}": "{value}" }} }}\n'
        "  }\n"
        "}\n"
        "```\n\n"
        "**Claude Desktop** — `claude_desktop_config.json` has no header field for HTTP "
        f"servers, so Claude Desktop cannot present the `{header}` header this server "
        "requires; for a personal Desktop server regenerate with `--auth env-token`.\n\n"
        "**Promptise agent** — `HTTPServerSpec` sends the header on every request:\n\n"
        "```python\n"
        "from promptise import build_agent, HTTPServerSpec\n"
        "\n"
        "agent = await build_agent(\n"
        '    model="openai:gpt-5-mini",\n'
        f'    servers={{"{name}": HTTPServerSpec(url="{_LOCAL_MCP_URL}", {spec_auth})}},\n'
        ")\n"
        "```\n"
    )


def _connect_section(plan: MCPcastPlan) -> str:
    """The README's *Connect an AI* body: snippets that work under the plan's auth mode."""
    body = (
        _http_snippets(plan)
        if plan.api.auth in (AuthMode.PASSTHROUGH, AuthMode.API_KEY)
        else _stdio_snippets(plan)
    )
    return _client_note(plan) + body


def _insecure_http_callout(plan: MCPcastPlan) -> str:
    """The README warning for a plan whose upstream is plain http on a non-loopback host."""
    hosts = plain_http_hosts(plan)
    if not hosts:
        return ""
    shown = ", ".join(map(_md_code, hosts))
    return (
        f"> **The upstream is plain `http://` ({shown}).** The server refuses to send the "
        "credential over an unencrypted connection — every call fails with "
        "`UPSTREAM_INSECURE` — until you set `MCPCAST_ALLOW_INSECURE_HTTP=1` in its "
        "environment, which accepts that anyone on the path can read the credential. The "
        "generated tests set it for themselves. Prefer an `https://` base URL "
        "(`MCPCAST_BASE_URL` overrides the plan's).\n\n"
    )


