def _server() -> MCPServer:
    """This module's ``server``, built on first use and then reused.

    Building reads the environment (credentials, client keys), so it happens
    when the server is first needed rather than at import: tools and
    evaluations import this module to reach ``build_server`` on their own terms.
    """
    built = globals().get("server")
    if built is None:
        built = globals()["server"] = build_server()
    return built


def __getattr__(name: str) -> Any:
    # `promptise serve server:server` and `module.server` resolve through here (PEP 562).
    if name == "server":
        return _server()
    raise AttributeError(f"module {{__name__!r}} has no attribute {{name!r}}")


