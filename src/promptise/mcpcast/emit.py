def _signature(tool: ToolPlan) -> tuple[list[str], list[tuple[str, str]], dict[str, str]]:
    """``(parameter declarations, [(wire_name, python_expr)], {wire: identifier})``."""
    taken: set[str] = set()
    required: list[str] = []
    optional: list[str] = []
    args: list[tuple[str, str]] = []
    idents: dict[str, str] = {}
    nulls = _null_params(tool)
    for wire, param in tool.params.items():
        if param.hidden:
            # Laid out where it will sit: an entry of the ``args`` dict, twelve
            # columns in, after the key.
            args.append((wire, _literal(param.default, 12, len(_py_str(wire)) + 2)))
            continue
        ident = python_identifier(wire, taken)
        idents[wire] = ident
        typ = python_type(param.json_schema)
        if param.required:
            # A required body property the spec lets be null accepts None and
            # sends it as JSON null (see _null_params): it cannot be omitted, so
            # None is the caller's explicit null.
            nullable = typ != "Any" and wire in nulls
            required.append(f"{ident}: {typ}{' | None' if nullable else ''}")
        else:
            annotation = "Any" if typ == "Any" else f"{typ} | None"
            optional.append(f"{ident}: {annotation} = None")
        args.append((wire, ident))
    # ``ctx`` is injected by the server (not part of the tool's input schema);
    # it goes first so optional parameters can carry ``= None`` defaults.
    return ["ctx: RequestContext", *required, *optional], args, idents


def _null_params(tool: ToolPlan) -> frozenset[str]:
    """Required parameters whose explicit ``null`` the server sends as JSON ``null``.

    Only a JSON body property can carry a null (a path or query string
    cannot), and only a required one is unambiguous: an optional
    parameter's ``None`` means "not given" and is left out of the request.
    """
    return frozenset(
        name
        for name, param in tool.params.items()
        if param.required
        and not param.hidden
        and _nullable(param.json_schema)
        and all(
            name in r.params and r.params[name].location == "body" and r.body_encoding == "json"
            for r in tool.routes
        )
    )


def _shape_hint(schema: dict[str, Any], name: str) -> str | None:
    """A compact example of a structured parameter's shape, if it has one."""
    if not (
        "properties" in schema or "items" in schema or schema.get("type") in ("object", "array")
    ):
        return None
    try:
        rendered = json.dumps(example_value(schema, name), ensure_ascii=False, default=str)
    except (TypeError, ValueError):
        return None
    if len(rendered) > _MAX_SHAPE_CHARS:
        rendered = rendered[: _MAX_SHAPE_CHARS - 1] + "…"
    return rendered


_MAX_DESCRIPTION_CHARS = 8000
"""Longest tool description the generated ``@server.tool`` declares.  The plan keeps
every text in full; the caps below apply at render time, so a bloated or hostile spec
cannot turn one ``tools/list`` into megabytes the consuming model pays for on every turn."""
_MAX_PROSE_CHARS = 3000
"""The tool's own description text."""
_MAX_EXAMPLE_CHARS = 1500
"""The ``Example:`` line — and the ``Always sends:`` and ``Provide one of:`` lines."""
_MAX_PARAM_DESC_CHARS = 600
"""One parameter's description."""
_MAX_ENUM_ENTRIES = 12
_MAX_ENUM_ENTRY_CHARS = 60
_MORE_PARAMS = "  … and {n} more parameters (see the input schema)"


def _clip(text: str, limit: int) -> str:
    """*text* cut to *limit* characters, an ellipsis marking the cut."""
    if len(text) <= limit:
        return text
    return text[: limit - 1].rstrip() + "…"


def _tool_description(tool: ToolPlan, idents: dict[str, str]) -> str:
    """Tool description as the LLM will see it: prose + parameter notes + example.

    Parameters and the example are rendered under the Python identifiers the
    input schema exposes (``user_id``, not ``user-id``), so what the agent
    reads matches what it must send.  Every part is capped — see
    :data:`_MAX_DESCRIPTION_CHARS` — and :func:`clipped_descriptions` reports
    the tools where a cap bit.
    """
    return _describe_tool(tool, idents)[0]


def clipped_descriptions(plan: MCPcastPlan) -> list[str]:
    """Names of the tools whose rendered description had to be cut to the caps.

    The plan keeps the full text; the generated ``@server.tool`` description
    is what the agent reads.  A tool listed here has a description an agent
    cannot read in full — a spec ``example`` of many kilobytes, an enum of
    hundreds of long entries, a parameter description the size of a page —
    which a review should see.

    Args:
        plan: The plan a project is generated from.

    Returns:
        Tool names in plan order; empty when nothing was cut.
    """
    return [tool.name for tool in plan.tools if _describe_tool(tool, _signature(tool)[2])[1]]


def _describe_tool(tool: ToolPlan, idents: dict[str, str]) -> tuple[str, bool]:
    """``(description, clipped)`` — the capped description and whether any cap bit."""
    clipped = False

    def capped(text: str, limit: int) -> str:
        nonlocal clipped
        cut = _clip(text, limit)
        clipped = clipped or cut != text
        return cut

    prose = capped(tool.description.strip(), _MAX_PROSE_CHARS)
    tail: list[str] = []
    alternatives = _required_alternatives(tool, idents)
    if alternatives:
        tail += ["", capped("Provide one of: " + " | ".join(alternatives), _MAX_EXAMPLE_CHARS)]
    fixed = {
        idents.get(w, w): p.default
        for w, p in tool.params.items()
        if p.hidden and p.default is not None
    }
    if fixed:
        sends = ", ".join(f"{k}={json.dumps(v, default=str)}" for k, v in fixed.items())
        tail += ["", capped("Always sends: " + sends, _MAX_EXAMPLE_CHARS)]
    if tool.example:
        shown_example = {idents.get(k, k): v for k, v in tool.example.items()}
        rendered = json.dumps(shown_example, ensure_ascii=False, default=str)
        tail += ["", "Example: " + capped(rendered, _MAX_EXAMPLE_CHARS)]
    notes: list[str] = []
    for wire, param in tool.visible_params.items():
        shown = idents.get(wire, wire)
        parts = [
            f"{shown} ({_displayed_type(param.json_schema)}{', required' if param.required else ''})"
        ]
        if param.description:
            parts.append(capped(param.description.strip(), _MAX_PARAM_DESC_CHARS))
        extras: list[str] = []
        enum = _enum_of(param.json_schema)
        if enum:
            entries = [capped(str(e), _MAX_ENUM_ENTRY_CHARS) for e in enum[:_MAX_ENUM_ENTRIES]]
            more = len(enum) - len(entries)
            extras.append("one of: " + ", ".join(entries) + (f" … (+{more} more)" if more else ""))
        default = param.default
        if default is None:
            default = _unwrap_nullable(param.json_schema).get("default")
        if default is not None:
            extras.append(f"default {default!r}")
        shape = _shape_hint(param.json_schema, wire)
        if shape is not None:
            extras.append(f"e.g. {shape}")
        note = "  - " + ": ".join(parts)
        if extras:
            note += "; " + "; ".join(extras)
        notes.append(note)
    lines = [prose]
    if notes:
        # The parameter notes fill what the capped prose and tail leave of the
        # budget; past it the agent is pointed at the input schema, where every
        # parameter advertises its JSON Schema (see _advertised_schema).
        room = _MAX_DESCRIPTION_CHARS - len(prose) - sum(len(t) + 1 for t in tail)
        lines += ["", "Parameters:"]
        used = sum(len(line) + 1 for line in lines[1:])
        for index, note in enumerate(notes):
            left = len(notes) - index - 1
            stub = _MORE_PARAMS.format(n=left) if left else ""
            if used + len(note) + 1 + (len(stub) + 1 if stub else 0) > room:
                lines.append(_MORE_PARAMS.format(n=len(notes) - index))
                clipped = True
                break
            lines.append(note)
            used += len(note) + 1
    lines += tail
    return "\n".join(lines), clipped


def _required_alternatives(tool: ToolPlan, idents: dict[str, str]) -> list[str]:
    """For a multi-route tool, each route's visible required parameters."""
    if len(tool.routes) < 2:
        return []
    groups: list[str] = []
    for route in tool.routes:
        names = [idents.get(n, n) for n in route.required_params if not tool.params[n].hidden]
        groups.append(" + ".join(names) if names else "(no parameters)")
    return groups if len(set(groups)) > 1 else []


