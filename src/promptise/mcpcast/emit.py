_TENANT_APPROVALS = '''

def register_tenant_scoped_approvals(server: MCPServer, approver: PendingApprover) -> None:
    """Four-eyes review scoped to the reviewer's tenant.

    A reviewer only sees and decides calls made by their own tenant, and may
    never approve their own request.  (The SDK's stock admin tools are
    server-wide; in a multi-tenant server that would leak one tenant's
    arguments to another's reviewers.)
    """

    @server.tool(
        name="approvals_list",
        description="List this tenant's tool calls awaiting human approval.",
        auth=True,
        guards=[HasRole("approver")],
        tags=["approvals"],
    )
    async def approvals_list(ctx: RequestContext) -> list[dict[str, Any]]:
        tenant = getattr(ctx.client, "tenant_id", None)
        return [p for p in approver.pending() if p.get("tenant_id") == tenant]

    @server.tool(
        name="approvals_decide",
        description="Approve or deny one of this tenant's pending tool calls by request id.",
        auth=True,
        guards=[HasRole("approver")],
        tags=["approvals"],
    )
    async def approvals_decide(
        ctx: RequestContext, request_id: str, approve: bool, reason: str = ""
    ) -> dict[str, Any]:
        tenant = getattr(ctx.client, "tenant_id", None)
        entry = next((p for p in approver.pending() if p["request_id"] == request_id), None)
        if entry is None or entry.get("tenant_id") != tenant:
            raise ToolError(
                f"No pending request {request_id!r} for tenant {tenant!r}", code="NOT_FOUND"
            )
        if entry.get("client_id") == ctx.client_id:
            raise ToolError("A caller may not approve their own request", code="ACCESS_DENIED")
        resolved = approver.decide(
            request_id, approve, reviewer_id=ctx.client_id, reason=reason or None
        )
        return {"request_id": request_id, "approved": approve, "resolved": resolved}
'''


