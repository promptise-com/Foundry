def _test_call(tool: ToolPlan, base_url: str) -> tuple[dict[str, Any], RoutePlan, str]:
    """Arguments that select the tool's first route, and the request path they produce.

    The arguments are keyed by the Python identifiers the tool's input schema
    exposes (``user_id``, ``from_``) — the same mapping :func:`_signature`
    builds — because that is what a client must send; the path substitution
    works from the wire names.
    """
    _, _, idents = _signature(tool)
    route = tool.routes[0]
    by_wire: dict[str, Any] = {}
    for name in route.required_params:
        param = tool.params[name]
        if param.hidden:
            continue
        if tool.example and name in tool.example:
            by_wire[name] = tool.example[name]
        else:
            by_wire[name] = json.loads(
                json.dumps(example_value(param.json_schema, name), default=str),
                parse_constant=str,
            )
    path = urlsplit(route.base_url or base_url).path.rstrip("/") + route.path
    for name, spec in route.params.items():
        if spec.location != "path":
            continue
        value = by_wire.get(name, tool.params[name].default if tool.params[name].hidden else None)
        path = path.replace("{" + (spec.wire_name or name) + "}", quote(str(value), safe=""))
    args = {idents.get(name, name): value for name, value in by_wire.items()}
    return args, route, path


