"""Code generation for ``promptise mcpcast`` — plan → project.

Emits a real, installable Promptise :class:`~promptise.mcp.server.MCPServer`
project the developer can read, test, diff and ship:

.. code-block:: text

    <name>-mcp/
    ├── mcpcast.plan.yaml     # the editable source of truth
    ├── server.py             # launcher: runs without installing; `promptise serve server:server`
    ├── pyproject.toml        # pip install -e .  →  the `<name>-mcp` command      (scaffold)
    ├── README.md
    ├── .env.example / Dockerfile / .gitignore                                    (scaffold)
    ├── <name>_mcp/
    │   ├── __init__.py       # build_server(), __version__
    │   ├── __main__.py       # python -m <name>_mcp [--transport http]
    │   ├── config.py         # constants from the plan + MCPCAST_* environment
    │   ├── upstream.py       # the HTTP client: routes, auth per mode, error mapping
    │   ├── approval.py       # the human approval gate
    │   ├── server.py         # build_server(): assembly
    │   └── tools/            # one module per resource, every @server.tool
    └── tests/                # conftest.py + test_tools.py: listing, routing, approval

Derived files are regenerated from the plan on every run; the scaffold files
(:data:`SCAFFOLD_ONCE`) are written once and then belong to the developer.
The package depends only on ``promptise`` and ``httpx``.  Every tool is a
plain ``@server.tool(...)`` function calling the upstream API; the plan's
``requires_approval`` flags wire straight into
:class:`~promptise.mcp.server.ApprovalGateMiddleware`.  ``build_server(
approval_handler=..., http_client=...)`` lets evaluations and tests inject an
auto-approver or a mock transport without touching the tool code.

Plan text never lands in generated source outside a string literal: names
are pattern-restricted, free text is emitted as an escaped literal, module
docstrings have control characters, backslashes and closing quotes
neutralised, and lone surrogates are replaced before anything is written, so
a hostile spec cannot turn ``info.title`` into code.  The other files hold
the same line: ``pyproject.toml`` escapes its description for TOML,
``README.md`` escapes Markdown, and the plan schema refuses a ``base_url``
that is not a single URL token before it can reach ``.env.example``.
"""

