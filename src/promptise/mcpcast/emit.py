def _names_assertion(plan: MCPcastPlan) -> str:
    """``assert names >= {...}`` for the plan's tools, block-formatted when long."""
    if not plan.tools:
        return "    assert names == names  # the plan exposes no tools under this profile"
    names = sorted(t.name for t in plan.tools)
    flat = "    assert names >= {" + ", ".join(_py_str(n) for n in names) + "}"
    if _columns(flat) <= _WIDTH:
        return flat
    return "    assert names >= {\n" + "".join(f"        {_py_str(n)},\n" for n in names) + "    }"


def _def_line(name: str, params: str) -> list[str]:
    """``async def name(params) -> None:`` on one line when it fits, else wrapped.

    The test names are ``test_<tool>_calls_<method>`` and
    ``test_<tool>_needs_approval``: with the 64-character tool name limit
    the wrapped form's first line, ``async def name(``, stays within the
    margin.
    """
    flat = f"async def {name}({params}) -> None:"
    if len(flat) <= _WIDTH:
        return [flat]
    return [f"async def {name}(", f"    {params}", ") -> None:"]


def _call_lines(client: str, tool: str, args: dict[str, Any]) -> list[str]:
    """``reply = await client.call_tool("tool", {...})``, block-formatted when long."""
    flat = f"    reply = await {client}.call_tool({_py_str(tool)}, {_literal(args)})"
    if _columns(flat) <= _WIDTH and "\n" not in flat:
        return [flat]
    return [
        f"    reply = await {client}.call_tool(",
        f"        {_py_str(tool)},",
        f"        {_literal(args, 8)},",
        "    )",
    ]


def _assert_equals(
    expression: str, expected: str, lines: Callable[[str, int], list[str]] = _string_lines
) -> str:
    """``    assert expression == "expected"``, the literal parenthesised when too wide.

    A long path or tool name moves into ``(\n        "…"\n    )`` — split into
    adjacent literals by *lines* if it is longer than a line — which is how
    the formatter keeps it and what keeps the line within the margin.
    """
    head = f"    assert {expression} == "
    return head + "\n".join(_wrapped_string(expected, 4, len(head) - 4, tail=0, lines=lines))


