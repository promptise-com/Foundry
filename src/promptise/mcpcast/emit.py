_MAX_IDENT_CHARS = 56
"""Longest identifier a wire parameter becomes.  A signature line is eight columns of
indentation, the identifier, the widest annotation the generator emits
(``: dict[str, Any] | None = None,``, 31 columns) and at most a one-character keyword
suffix: 96 columns, inside the 100 the generated project's formatter enforces.  The
uniqueness suffix is applied inside the cap, as :func:`~promptise.mcpcast.plan.derive_tool_name`
does for tool names."""


def python_identifier(wire_name: str, taken: set[str] | None = None) -> str:
    """A safe Python parameter name for a wire parameter (``user-id`` → ``user_id``).

    Keywords and the names the generated handler body relies on get a
    trailing underscore; *taken* makes the result unique within a signature.
    Names longer than :data:`_MAX_IDENT_CHARS` are cut there (before the
    keyword check, so the cut name is checked too); the wire name is kept in
    full in the generated ``args`` mapping and on the wire.
    """
    ident = _IDENT.sub("_", wire_name).strip("_") or "param"
    if ident[0].isdigit():
        ident = f"p_{ident}"
    ident = ident[:_MAX_IDENT_CHARS].rstrip("_")
    if (
        is_python_keyword(ident)
        or ident in RESERVED_PARAM_NAMES
        or ident.startswith("__")
        or ident.startswith("model_")  # pydantic's protected namespace
    ):
        ident = f"{ident}_"
    if taken is not None:
        candidate, n = ident, 2
        while candidate in taken:
            suffix = f"_{n}"
            candidate = f"{ident[: _MAX_IDENT_CHARS - len(suffix)]}{suffix}"
            n += 1
        taken.add(candidate)
        return candidate
    return ident


def _unwrap_nullable(schema: dict[str, Any]) -> dict[str, Any]:
    """``anyOf: [{type: X}, {type: "null"}]`` (FastAPI's ``Optional[X]``) → ``{type: X}``."""
    for key in ("anyOf", "oneOf"):
        options = schema.get(key)
        if isinstance(options, list):
            real = [o for o in options if isinstance(o, dict) and o.get("type") != "null"]
            if len(real) == 1:
                merged = {k: v for k, v in schema.items() if k not in ("anyOf", "oneOf")}
                return {**real[0], **merged}
    return schema


def python_type(schema: dict[str, Any]) -> str:
    """The Python annotation for a JSON Schema fragment."""
    schema = _unwrap_nullable(schema)
    typ = schema.get("type")
    if isinstance(typ, list):
        non_null = [t for t in typ if t != "null"]
        typ = non_null[0] if len(non_null) == 1 else None
    mapping = {
        "string": "str",
        "integer": "int",
        "number": "float",
        "boolean": "bool",
        "array": "list[Any]",
        "object": "dict[str, Any]",
    }
    if typ in mapping:
        return mapping[str(typ)]
    if "properties" in schema:
        return "dict[str, Any]"
    if "items" in schema:
        return "list[Any]"
    return "Any"


def _displayed_type(schema: dict[str, Any]) -> str:
    """The type shown to the agent, derived from the schema's shape."""
    schema = _unwrap_nullable(schema)
    typ = schema.get("type")
    if isinstance(typ, list):
        non_null = [str(t) for t in typ if t != "null"]
        return "/".join(non_null) if non_null else "null"
    if typ:
        return str(typ)
    if "properties" in schema or any(k in schema for k in ("oneOf", "anyOf", "allOf")):
        return "object"
    if "items" in schema:
        return "array"
    return "string"


_WIDTH = 100  # the line length the generated project's own [tool.ruff] declares
_DOC_WIDTH = 84  # the width generated docstrings and comments are wrapped to when they can be


def _columns(text: str) -> int:
    """The display width of *text* the way ruff measures a line.

    East Asian wide and fullwidth characters (CJK, most emoji) take two
    columns; combining marks and zero-width format characters take none.
    Every fit decision in this module uses it, so a description in Japanese
    is laid out exactly as the formatter would lay it out.
    """
    width = 0
    for ch in text:
        if unicodedata.combining(ch) or unicodedata.category(ch) in ("Mn", "Me", "Cf"):
            continue
        width += 2 if unicodedata.east_asian_width(ch) in ("W", "F") else 1
    return width


def _cut(text: str, columns: int) -> str:
    """*text* within *columns* display columns, cut at a word boundary with an ellipsis."""
    if _columns(text) <= columns:
        return text
    kept, width = "", 0
    for ch in text:
        width += _columns(ch)
        if width > columns - 1:
            break
        kept += ch
    return kept.rsplit(" ", 1)[0].rstrip(",;:") + "…"


def _writable(text: str) -> str:
    """*text* with lone UTF-16 surrogates replaced — every generated file is written as UTF-8."""
    return text.encode("utf-8", "replace").decode("utf-8")


def _py_str(text: str) -> str:
    """A Python string literal: double-quoted unless single quotes need fewer escapes."""
    text = _writable(text)
    if text.count('"') > text.count("'"):
        return repr(text)
    return json.dumps(text, ensure_ascii=False)


def _literal(value: Any, indent: int = 0, prefix: int = 0, wrap_strings: bool = False) -> str:
    """A Python source literal for a JSON-compatible value.

    Collections that do not fit in the remaining width are laid out one entry
    per line, continuation lines indented *indent* spaces past the opening
    bracket — the way a formatter would write them.  *indent* is the column
    the literal starts at and *prefix* the width of what precedes it on that
    line (``tags=``); a trailing comma is always allowed for.  Non-finite
    numbers (``inf``, ``nan``) are not JSON and are rendered as strings.
    With *wrap_strings*, a string that does not fit where it stands becomes
    parenthesised adjacent literals (spec prose in a schema), which the
    formatter keeps as written.
    """
    value = json.loads(json.dumps(value, default=str), parse_constant=str)
    return _lay_out(value, indent, prefix, wrap_strings)


def _fits(indent: int, prefix: int, flat: str, tail: int = 1) -> bool:
    """Whether *flat* fits on its line: *indent* and *prefix* before it, *tail* columns after.

    *tail* is 1 when a comma or a closing bracket follows (an argument, an
    element, an entry) and 0 at the end of a statement — the formatter joins
    a one-element tuple or a parenthesised string back onto one line when
    the statement fits exactly, so the allowance must be exact.
    """
    return indent + prefix + _columns(flat) + tail <= _WIDTH and "\n" not in flat


def _lay_out(value: Any, indent: int, prefix: int = 0, wrap_strings: bool = False) -> str:
    """Render *value* once, linearly: every child is laid out exactly one time."""
    if isinstance(value, str):
        if wrap_strings:
            return "\n".join(_wrapped_string(value, indent, prefix))
        return _py_str(value)
    if isinstance(value, bool) or value is None:
        return repr(value)
    if isinstance(value, (int, float)):
        return repr(value)
    pad = " " * (indent + 4)
    if isinstance(value, dict):
        entries = [
            (key, _lay_out(v, indent + 4, _columns(key) + 2, wrap_strings))
            for key, v in ((_py_str(str(k)), v) for k, v in value.items())
        ]
        flat = "{" + ", ".join(f"{k}: {v}" for k, v in entries) + "}"
        if _fits(indent, prefix, flat):
            return flat
        return "{\n" + "".join(f"{pad}{k}: {v},\n" for k, v in entries) + " " * indent + "}"
    if isinstance(value, list):
        items = [_lay_out(v, indent + 4, 0, wrap_strings) for v in value]
        flat = "[" + ", ".join(items) + "]"
        if _fits(indent, prefix, flat):
            return flat
        return "[\n" + "".join(f"{pad}{item},\n" for item in items) + " " * indent + "]"
    return repr(value)


def _names_tuple(names: tuple[str, ...], indent: int = 0, prefix: int = 0, tail: int = 1) -> str:
    """``("a", "b")`` / ``("a",)`` with double quotes, one name per line when too wide."""
    if not names:
        return "()"
    if len(names) == 1:
        flat = f"({_py_str(names[0])},)"
    else:
        flat = "(" + ", ".join(_py_str(n) for n in names) + ")"
    if _fits(indent, prefix, flat, tail):
        return flat
    pad = " " * (indent + 4)
    return "(\n" + "".join(f"{pad}{_py_str(n)},\n" for n in names) + " " * indent + ")"


def _call(func: str, args: list[str], indent: int, prefix: int = 0, tail: int = 1) -> str:
    """``func(a, b)`` on one line when it fits, else one argument per line."""
    flat = f"{func}({', '.join(args)})"
    if _fits(indent, prefix, flat, tail):
        return flat
    pad = " " * (indent + 4)
    return f"{func}(\n" + "".join(f"{pad}{a},\n" for a in args) + " " * indent + ")"


def _chunks(text: str, width: int) -> list[str]:
    """*text* split into pieces of at most *width* characters, at spaces where possible.

    Nothing is altered — tabs are not expanded, whitespace is not collapsed —
    so the pieces concatenate back to exactly *text*.
    """
    return textwrap.wrap(
        text,
        width=max(1, width),
        expand_tabs=False,
        replace_whitespace=False,
        break_long_words=True,
        break_on_hyphens=False,
        drop_whitespace=False,
    ) or [""]


def _string_lines(text: str, indent: int, width: int = _WIDTH) -> list[str]:
    """*text* as adjacent string literals, one per line, each within *width* columns.

    Newlines in *text* are kept inside the literals, so the concatenation is
    exactly *text*; a hostile spec still cannot leave the string.  The width
    is that of the rendered literal: a piece whose escapes (quotes, control
    characters) or wide characters push it past the margin is split again.
    """

    def fits(piece: str) -> bool:
        return indent + _columns(_py_str(piece)) <= width

    room = max(20, width - indent - 4)
    pieces: list[str] = []
    for line in text.splitlines(keepends=True):
        body = line.rstrip("\r\n")
        end = line[len(body) :]
        chunks = _chunks(body, room)
        chunks[-1] += end
        queue = list(reversed(chunks))
        while queue:
            chunk = queue.pop()
            if fits(chunk) or len(chunk) <= 1:
                pieces.append(chunk)
                continue
            # Too wide as rendered: keep the longest prefix that fits — cut at
            # its last space when it has one — and queue the rest.
            head = next(
                (chunk[:n] for n in range(len(chunk) - 1, 0, -1) if fits(chunk[:n])), chunk[:1]
            )
            if " " in head[1:]:
                head = head[: head.rindex(" ") + 1]
            pieces.append(head)
            queue.append(chunk[len(head) :])
    return [" " * indent + _py_str(piece) for piece in pieces] or [" " * indent + '""']


def _path_lines(path: str, indent: int, width: int = _WIDTH) -> list[str]:
    """A URL path as adjacent string literals split at ``/`` boundaries, one per line.

    Each line is within *width* columns as rendered; a single segment wider
    than a line is cut where it must be.  The pieces concatenate back to
    exactly *path*.
    """

    def fits(piece: str) -> bool:
        return indent + _columns(_py_str(piece)) + 1 <= width

    pieces: list[str] = []
    current = ""
    for segment in re.split(r"(?=/)", path):
        if not segment:
            continue
        if current and not fits(current + segment):
            pieces.append(current)
            current = ""
        while segment and not fits(current + segment):
            cut = len(segment) - 1
            while cut > 1 and not fits(current + segment[:cut]):
                cut -= 1
            pieces.append(current + segment[:cut])
            current, segment = "", segment[cut:]
        current += segment
    pieces.append(current)
    return [" " * indent + _py_str(piece) for piece in pieces]


def _wrapped_string(
    text: str,
    indent: int,
    prefix: int = 0,
    tail: int = 1,
    lines: Callable[[str, int], list[str]] = _string_lines,
) -> list[str]:
    """``(\n    'part'\n    'part'\n)`` when *text* does not fit on one line, else ``'text'``.

    *prefix* is the width of what precedes the literal on its line
    (``description=``) and *tail* what follows it (a comma), so the one-line
    form is only used when it really fits.  A literal that fits on its own
    line inside the parentheses is emitted as one piece — the formatter joins
    implicit concatenations that fit; a longer one is split into pieces by
    *lines* (prose at spaces, a path at slashes).
    """
    flat = _py_str(text)
    if _fits(indent, prefix, flat, tail):
        return [flat]
    if indent + 4 + _columns(flat) <= _WIDTH:
        return ["(", " " * (indent + 4) + flat, " " * indent + ")"]
    return ["(", *lines(text, indent + 4), " " * indent + ")"]


