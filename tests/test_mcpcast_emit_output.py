class TestReadmeEscapesPlanText:
    def test_dropped_ids_and_hidden_defaults_are_code_spans(self):
        plan = _plan(profile=SafetyProfile.FULL)
        hostile_id = "x` | [phish](https://evil.test/login) <img src=x onerror=alert(1)> `"
        tool = plan.tool("create_ticket")
        params = dict(tool.params)
        params["mode`[phish](https://evil.test)`"] = ParamPlan(
            hidden=True, default="[img](https://evil.test/x) <img src=y>"
        )
        plan = plan.model_copy(
            update={
                "dropped": [
                    *plan.dropped,
                    DroppedOp.model_construct(operation_id=hostile_id, reason="hand-edited"),
                ],
                "tools": [
                    t.model_copy(update={"params": params}) if t is tool else t for t in plan.tools
                ],
            }
        )
        md = render_readme(plan)
        prose = re.sub(r"``.*?``|`[^`\n]*`", "", md)  # code spans render literally anyway
        assert "evil.test" not in prose and "<img" not in prose  # no live link, no tag
        assert "](https://docs.promptise.com" in prose  # the README's own link is untouched
