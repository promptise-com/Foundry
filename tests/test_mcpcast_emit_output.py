def _plan(**kw) -> MCPcastPlan:
    return mcpcast(SPEC, name="helpdesk", **kw)


def _snapshot(root: Path) -> dict[str, bytes]:
    """Every file under *root* with its content — to prove a refusal wrote nothing."""
    return {
        p.relative_to(root).as_posix(): p.read_bytes()
        for p in root.rglob("*")
        if p.is_file() and "__pycache__" not in p.parts
    }


def _many_tools_spec(tag: str, count: int) -> dict:
    """*count* GET operations under one tag — one tools module with a long docstring."""
    return {
        "openapi": "3.0.0",
        "info": {"title": "Warehouse"},
        "servers": [{"url": "https://wh.example"}],
        "paths": {
            f"/{tag}/kind-{i:03d}": {
                "get": {
                    "operationId": f"list{tag.title()}Kind{i:03d}",
                    "summary": f"List every {tag} record of kind {i}",
                    "tags": [tag],
                }
            }
            for i in range(count)
        },
    }


