        assert "a file without the generated header" in row and "regeneration refuses" in row
        plan_row = next(
            line for line in md.splitlines() if line.startswith("| `mcpcast.plan.yaml`")
        )
        assert "`api.name` fixes the package (`helpdesk_mcp/`)" in plan_row
        assert "`helpdesk-mcp` command" in plan_row and "is refused" in plan_row


