def _connect_section(md: str) -> str:
    return md[md.index("## Connect an AI") : md.index("## Tools")]


def _snippet_call(section: str, cls: str) -> str:
    """The one ``cls(...)`` call in the Promptise snippet — balanced parentheses."""
    start = section.index(f"{cls}(") + len(cls)
    depth, end = 0, start
    for end, char in enumerate(section[start:], start):
        depth += (char == "(") - (char == ")")
        if depth == 0:
            break
    return cls + section[start : end + 1]


class TestClientSnippetsMatchAuthMode:
    def test_env_token_snippets_all_carry_the_credential(self):
        section = _connect_section(render_readme(_plan(auth=AuthMode.ENV_TOKEN)))
        assert "does not inherit your shell" in section
        assert (
            section.count('"env": {"MCPCAST_UPSTREAM_TOKEN": "Bearer <your API token>"}') == 2
        )  # Claude Desktop and Cursor
        assert (
            'claude mcp add helpdesk -e MCPCAST_UPSTREAM_TOKEN="Bearer <your API token>" -- python'
            in section
        )
        assert 'env={"MCPCAST_UPSTREAM_TOKEN": "Bearer <your API token>"}' in section
        spec = eval(_snippet_call(section, "StdioServerSpec"), {"StdioServerSpec": StdioServerSpec})
        assert spec.env == {"MCPCAST_UPSTREAM_TOKEN": "Bearer <your API token>"}
        assert spec.command == "python" and spec.args == ["server.py"]
        assert "HTTPServerSpec" not in section

    @pytest.mark.parametrize(
        ("auth", "header", "value", "kwarg", "secret"),
        [
            (AuthMode.API_KEY, "x-api-key", "<key>", "api_key", "<key>"),
            (AuthMode.PASSTHROUGH, "Authorization", "Bearer <token>", "bearer_token", "<token>"),
        ],
        ids=["api-key", "passthrough"],
    )
    def test_header_modes_get_http_snippets_and_no_stdio_config(
        self, auth, header, value, kwarg, secret
    ):
        section = _connect_section(render_readme(_plan(auth=auth)))
        assert f"needs an `{header}` header on every request" in section
        assert "StdioServerSpec" not in section and "/absolute/path/to/server.py" not in section
        assert "python server.py --transport http" in section
        assert (
            f"claude mcp add helpdesk --transport http http://127.0.0.1:8080/mcp "
            f'--header "{header}: {value}"' in section
        )
        assert (
            f'"helpdesk": {{ "url": "http://127.0.0.1:8080/mcp", "headers": {{ "{header}": "{value}" }} }}'
            in section
        )
        assert "`claude_desktop_config.json` has no header field for HTTP servers" in section
        call = _snippet_call(section, "HTTPServerSpec")
        assert call == f'HTTPServerSpec(url="http://127.0.0.1:8080/mcp", {kwarg}="{secret}")'
        spec = eval(call, {"HTTPServerSpec": HTTPServerSpec})  # the snippet is a real spec
        assert spec.url == "http://127.0.0.1:8080/mcp"
        assert getattr(spec, kwarg).get_secret_value() == secret

    def test_none_snippets_stay_plain_stdio(self):
        section = _connect_section(render_readme(_plan(auth=AuthMode.NONE)))
        assert "claude mcp add helpdesk -- python /absolute/path/to/server.py" in section
        assert (
            '"env"' not in section and "HTTPServerSpec" not in section and "header" not in section
        )
        assert 'StdioServerSpec(command="python", args=["server.py"])' in section

    def test_passthrough_claims_only_the_current_request(self):
        md = render_readme(_plan(auth=AuthMode.PASSTHROUGH))
        assert "every agent acts with its own user's permissions" not in md
        assert "a call acts with the caller's credential on that request" in md


