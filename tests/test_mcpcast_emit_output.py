class TestDescriptionCaps:
    def test_hostile_spec_stays_within_the_cap(self):
        plan = mcpcast(
            _bloated_spec(), name="bloat", profile=SafetyProfile.FULL, auth=AuthMode.NONE
        )
        tool = plan.tool("make_thing")
        assert len(tool.example["blob"]) == 100_000  # the plan keeps the full text
        assert len(tool.params["kind"].description) == 5000
        text = _tool_description(tool, _signature(tool)[2])
        assert len(text) <= _MAX_DESCRIPTION_CHARS
        example = next(line for line in text.splitlines() if line.startswith("Example: "))
        assert len(example) <= len("Example: ") + _MAX_EXAMPLE_CHARS and example.endswith("…")
        kind = next(line for line in text.splitlines() if line.startswith("  - kind "))
        assert "k" * _MAX_PARAM_DESC_CHARS not in kind and "k" * 500 + "…" in kind
        assert "one of: 000-" + "v" * 55 + "…, 001-" in kind and " … (+38 more)" in kind
        assert re.search(r"^  … and \d+ more parameters \(see the input schema\)$", text, re.M)
        assert text.count("\n  - field_") < 200
        assert clipped_descriptions(plan) == ["make_thing"]
        src = render_project(plan)["bloat_mcp/tools/things.py"]
        assert "b" * 2000 not in src  # nothing above the cap reaches the module either

    def test_ordinary_descriptions_are_untouched(self):
        plan = _plan(profile=SafetyProfile.FULL)
        assert clipped_descriptions(plan) == []
        tool = plan.tool("create_ticket")
        text = _tool_description(tool, _signature(tool)[2])
        assert "…" not in text and "more parameters" not in text
        assert "  - subject (string, required)" in text

    def test_enum_beyond_twelve_entries_is_counted_not_clipped(self):
        spec = {
            "openapi": "3.0.0",
            "info": {"title": "Flags"},
            "servers": [{"url": "https://f.example"}],
            "paths": {
                "/flags": {
                    "get": {
                        "operationId": "listFlags",
                        "parameters": [
                            {
                                "name": "colour",
                                "in": "query",
                                "schema": {"type": "string", "enum": [f"c{i}" for i in range(15)]},
                            }
                        ],
                    }
                }
            },
        }
        plan = mcpcast(spec, name="flags", auth=AuthMode.NONE)
        tool = plan.tool("list_flags")
        text = _tool_description(tool, _signature(tool)[2])
        assert "one of: c0, c1, c2, c3, c4, c5, c6, c7, c8, c9, c10, c11 … (+3 more)" in text
        assert clipped_descriptions(plan) == []  # a long enum is expected; nothing was cut


